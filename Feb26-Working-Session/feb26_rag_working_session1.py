### 5. Add Docs to VectorDB

## OpenAIEmbeddings → converts text into numerical vectors
## FAISS → local vector database for similarity search
## Preparing: Text ➜ Embeddings ➜ Vector Index

from langchain_openai import OpenAIEmbeddings
from langchain_community.vectorstores import FAISS

## This model:
## Takes text chunks
## Converts each chunk into a vector (like a fingerprint)
## Each chunk becomes something like:
## [0.023, -0.892, 0.442, ...]

### 1. Create Embeddings Model
embeddings = OpenAIEmbeddings(
    model="openai/text-embedding-3-small",
    api_key=openrouter_key,
    base_url="https://openrouter.ai/api/v1"
)


### 2. create FAISS vector store

## It sends text → embedding model
## Gets numerical vector
## Stores vector inside FAISS index
vectorstore = FAISS.from_documents(
    documents=splits,
    embedding=embeddings
)

print("FAISS index created successfully")

print("Total vectors:", vectorstore.index.ntotal)
print("Total documents:", len(vectorstore.docstore._dict))
print(vectorstore.index_to_docstore_id)

doc_id = list(vectorstore.index_to_docstore_id.values())[0]

# Get FAISS index position
faiss_index = list(vectorstore.index_to_docstore_id.keys())[0]

# Get embedding vector
embedding = vectorstore.index.reconstruct(faiss_index)

# Get document
doc = vectorstore.docstore.search(doc_id)

print({
    "ids": [doc_id],
    "embeddings": [embedding],
    "documents": [doc.page_content]
})

### Create a Helper Function to display document id, embeddings and documents
def faiss_get(vectorstore, doc_id):
    for idx, stored_id in vectorstore.index_to_docstore_id.items():
        if stored_id == doc_id:
            embedding = vectorstore.index.reconstruct(idx)
            document = vectorstore.docstore.search(doc_id)
            return {
                "ids": [doc_id],
                "embeddings": [embedding],
                "documents": [document.page_content]
            }

