### 7. Augumentation

### What is happening here?

### pulling a predefined RAG prompt template from LangSmith Hub.

### This prompt typically looks like:

### Use the following context to answer the question.
     # If you don't know, say you don't know.

    # Context:
    # {context}

    # Question:
    # {question}

### This step is critical.
### This is what prevents hallucination.
### Because the model is explicitly instructed:
### Only use context
### Don’t make up answers
### That is the “A” (Augmentation) in RAG.

from langsmith import Client

client = Client()
prompt = client.pull_prompt("rlm/rag-prompt")

### 8. Setup LLM

#Using GPT-4o-mini via OpenRouter
#Temperature = 0 → deterministic output
#Good for factual RAG

import os
from langchain_openai import ChatOpenAI

llm = ChatOpenAI(
    model="openai/gpt-4o-mini",          # OpenRouter model name
    base_url="https://openrouter.ai/api/v1",
    temperature=0
)

# quick test
print(llm.invoke("Say hi in 1 line.").content)

from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser

### These are used to build the chain manually.

# This function:
# Takes retrieved chunks
# Combines them into one context string
# Feeds into prompt

def format_docs(docs):
  return "\n".join(doc.page_content for doc in docs)

### 9. RAG chain Code

### Retriever
# → Format docs
# → Insert into prompt
# → LLM
# → Output parser

rag_chain = ({"context": retriever | format_docs, "question": RunnablePassthrough()}
             | prompt
             | llm
             | StrOutputParser())

### Test RAG Chain Code
